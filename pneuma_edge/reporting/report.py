"""Генерация отчётов (JSON + Markdown + данные для визуализации)."""

from __future__ import annotations
from typing import Dict, Any, List
from pathlib import Path
import json


class ReportBuilder:
    def build(
        self,
        mode: str,
        scenario: str,
        frames: List[dict],
        reports: List[dict],
        reflections: List[dict],
        archetypal: List[dict] | None = None,
        war_summary: dict | None = None,
    ) -> Dict[str, Any]:
        result = {
            "project": "PNEUMA-Edge Unified",
            "version": "0.2.0",
            "mode": mode,
            "scenario": scenario,
            "steps": len(frames),
            "frames": frames,
            "reports": reports,
            "reflections": reflections,
            "visualization": self._viz_data(reports),
        }
        if mode == "archetypal":
            result["archetypal_layer"] = archetypal or []
            result["war_cycle_hypothesis"] = war_summary
            result["global_disclaimer"] = (
                "Все архетипические выводы имеют статус "
                "archetypal_hypothesis_not_fact и не являются утверждением онтологии."
            )
        return result

    def _viz_data(self, reports: List[dict]) -> Dict[str, List]:
        return {
            "steps": [r["step"] for r in reports],
            "arousal": [r["arousal"] for r in reports],
            "recovery": [r["recovery"] for r in reports],
            "risk": [r["risk"] for r in reports],
            "coherence": [r["coherence"] for r in reports],
        }

    def to_markdown(self, data: Dict[str, Any]) -> str:
        lines = [
            f"# PNEUMA-Edge Report ({data['mode']})",
            f"- Scenario: **{data['scenario']}**",
            f"- Steps: **{data['steps']}**",
            "",
        ]
        if data["reports"]:
            last = data["reports"][-1]
            lines += [
                "## Final state",
                f"- Risk: `{last['risk']:.3f}`",
                f"- Patterns: {', '.join(last['patterns']) or 'none'}",
                f"- Interpretation: {last['interpretation']}",
                "",
            ]
        if data.get("mode") == "archetypal" and data.get("war_cycle_hypothesis"):
            war = data["war_cycle_hypothesis"]
            lines += [
                "## War-cycle hypothesis (archetypal)",
                f"- Epistemic status: `{war.get('epistemic_status')}`",
                f"- Total harvested (metaphor): {war.get('total_harvested')}",
                f"- Living (model): {war.get('living')}",
                "",
            ]
        lines.append("---\n*Generated by PNEUMA-Edge Unified v0.2.0*")
        return "\n".join(lines)

    def export(self, data: Dict[str, Any], json_path: str, md_path: str | None = None) -> None:
        Path(json_path).write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
        if md_path:
            Path(md_path).write_text(self.to_markdown(data), encoding="utf-8")
